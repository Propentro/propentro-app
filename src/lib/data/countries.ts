export type Country = {
  code: string;
  name: string;
  flag: string;
};

function codeToFlag(code: string): string {
  return String.fromCodePoint(
    ...code
      .toUpperCase()
      .split('')
      .map((c) => 0x1f1e6 + c.charCodeAt(0) - 65)
  );
}

function c(code: string, name: string): Country {
  return { code, name, flag: codeToFlag(code) };
}

